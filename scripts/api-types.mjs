// Regenerates the web client's types from the app's OpenAPI document, the one schema both sides share.
// `--check` fails when the committed files are stale (CI).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const check = process.argv.includes("--check");
const SPEC = "crates/server/openapi.json";
const TYPES = "apps/web/src/api/schema.d.ts";

const spec =
  execFileSync("cargo", ["run", "--quiet", "--package", "dameless", "--bin", "dameless", "--", "openapi"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }).trimEnd() + "\n";
const header = "// Generated by `pnpm api` from crates/server/openapi.json. Do not edit.\n\n";
const types = header + astToString(await openapiTS(JSON.parse(spec)));

const stale = [
  [SPEC, spec],
  [TYPES, types],
].filter(([path, text]) => {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === text) return false;
  if (!check) writeFileSync(path, text);
  return true;
});

if (check && stale.length) {
  console.error(`Stale: ${stale.map(([path]) => path).join(", ")}. Run \`pnpm api\` and commit the result.`);
  process.exit(1);
}
console.log(stale.length ? `Wrote ${stale.map(([path]) => path).join(", ")}` : "API types are up to date.");
